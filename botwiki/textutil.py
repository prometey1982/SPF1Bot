"""Текстовая нормализация: стоп-слова, токенизация (общий источник).

Используется менеджером (тривиальные сообщения, стилевые признаки),
детектором кандидатов страниц (п. 9.4) и router (п. 11.1).
Без внешних библиотек: нижний регистр, буквенные токены ≥ 2 символов,
удаление стоп-слов и чисел. Словоформы/лемматизация — на будущее (алиасы).
"""

import re

STOPWORDS = {
    'и', 'в', 'во', 'не', 'что', 'он', 'на', 'я', 'с', 'со', 'как', 'а', 'то',
    'все', 'она', 'так', 'его', 'но', 'да', 'ты', 'к', 'у', 'же', 'вы', 'за',
    'бы', 'по', 'только', 'ее', 'мне', 'было', 'вот', 'от', 'меня', 'еще', 'нет',
    'о', 'из', 'ему', 'теперь', 'когда', 'даже', 'ну', 'вдруг', 'ли', 'если',
    'уже', 'или', 'ни', 'быть', 'был', 'него', 'до', 'вас', 'нибудь', 'опять',
    'уж', 'вам', 'ведь', 'там', 'потом', 'себя', 'ничего', 'ей', 'может', 'они',
    'тут', 'где', 'есть', 'надо', 'ней', 'для', 'мы', 'тебя', 'их', 'чем', 'была',
    'сам', 'чтоб', 'без', 'будто', 'чего', 'раз', 'тоже', 'себе', 'под', 'будет',
    'ж', 'тогда', 'кто', 'этот', 'того', 'потому', 'этого', 'какой', 'совсем',
    'ним', 'здесь', 'этом', 'один', 'почти', 'мой', 'тем', 'чтобы', 'нее', 'кажется',
    'сейчас', 'были', 'куда', 'зачем', 'сказать', 'всех', 'никогда', 'конечно',
    'всю', 'нету', 'при', 'об', 'хоть', 'после', 'над', 'тот', 'через', 'эти',
    # междометия/сленг-реакции — тривиальные
    'ок', 'окей', 'ага', 'ахах', 'угу', 'мда', 'хм', 'ого', 'лол', 'кек', 'лан',
    'неа', 'ауч', 'аа', 'оо', 'мм', 'эх', 'оу', 'вау',
}

_TOKEN_RE = re.compile(r'[a-zа-яё]{2,}', re.IGNORECASE)


def tokenize(text: str | None) -> list[str]:
    """Значимые токены текста (нижний регистр, без стоп-слов и чисел-только)."""
    if not text:
        return []
    return [t.lower() for t in _TOKEN_RE.findall(text) if t.lower() not in STOPWORDS]


def token_set(text: str | None) -> set[str]:
    return set(tokenize(text))
